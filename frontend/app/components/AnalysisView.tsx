'use client';

import { Brain, ListChecks, Search } from 'lucide-react';
import { timeAgo } from '../lib/format';
import type { Analysis } from '../lib/types';
import { Badge } from './ui';

export function AnalysisView({ analysis, now }: { analysis: Analysis; now: number | null }) {
  const isAi = analysis.source === 'gemini';
  const metrics = Object.entries(analysis.evidence?.metrics ?? {});

  return (
    <div className="space-y-3 text-sm">
      <div className="flex flex-wrap items-center gap-2">
        {isAi ? (
          <Badge tone="info" title="Generated by the language model from measured evidence only">
            <Brain size={11} /> AI · {analysis.model}
          </Badge>
        ) : (
          <Badge tone="muted" title={analysis.fallback_reason ?? 'Deterministic analysis'}>
            Rule-based analysis
          </Badge>
        )}
        <span className="text-[11px] text-slate-500">
          {timeAgo(analysis.created_at, now)}
          {isAi && analysis.latency_ms ? ` · ${analysis.latency_ms} ms` : ''}
        </span>
      </div>

      {!isAi && analysis.fallback_reason && (
        <p className="rounded-lg border border-white/5 bg-black/20 px-3 py-2 text-[11px] text-slate-500">Why not AI: {analysis.fallback_reason}</p>
      )}

      <p className="leading-relaxed text-slate-200">{analysis.summary}</p>

      <div>
        <h4 className="mb-1 flex items-center gap-1.5 text-[10px] font-semibold uppercase tracking-[0.18em] text-slate-400">
          <Search size={11} /> Likely cause
        </h4>
        <p className="text-slate-300">{analysis.likely_cause ?? 'Not determinable from the measured evidence.'}</p>
      </div>

      <div>
        <h4 className="mb-1 flex items-center gap-1.5 text-[10px] font-semibold uppercase tracking-[0.18em] text-slate-400">
          <ListChecks size={11} /> Recommended actions
        </h4>
        <ol className="list-decimal space-y-1 pl-5 text-slate-300">
          {analysis.recommended_actions.map((a) => (
            <li key={a}>{a}</li>
          ))}
        </ol>
      </div>

      {metrics.length > 0 && (
        <details className="group rounded-lg border border-white/5 bg-black/20 px-3 py-2">
          <summary className="cursor-pointer text-[11px] font-semibold uppercase tracking-wider text-slate-400">
            Evidence used ({analysis.evidence.samples ?? 0} samples, {analysis.evidence.window_seconds ?? 0}s window)
          </summary>
          <table className="mt-2 w-full text-left font-mono text-[11px] text-slate-300">
            <thead className="text-slate-500">
              <tr>
                <th className="py-1 font-normal">metric</th>
                <th className="font-normal">min</th>
                <th className="font-normal">avg</th>
                <th className="font-normal">max</th>
                <th className="font-normal">last</th>
              </tr>
            </thead>
            <tbody>
              {metrics.map(([name, s]) => (
                <tr key={name} className="border-t border-white/5">
                  <td className="py-1">{name}</td>
                  <td>{s.min}</td>
                  <td>{s.avg}</td>
                  <td>{s.max}</td>
                  <td>{s.last}</td>
                </tr>
              ))}
            </tbody>
          </table>
        </details>
      )}
    </div>
  );
}
